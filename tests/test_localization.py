def _pose3d(x=8.0, y=4.0, z=0.0, yaw_deg=0.0):
    """Create a Pose3d at the given position."""
    return Pose3d(
        Translation3d(x, y, z),
        Rotation3d(0, 0, math.radians(yaw_deg)),
    )


