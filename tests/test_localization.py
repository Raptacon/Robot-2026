class TestStdDevComputation:

    def test_multi_tag_uses_multi_tag_base(self):
        loc = _make_localization()
        # Use tag IDs that exist in the field layout; place estimated pose
        # very close to a real tag so distance scaling is ~1.0
        tag_pose = loc.field_layout.getTagPose(1)
        assert tag_pose is not None
        estimated = Pose3d(
            tag_pose.translation(), Rotation3d()
        )
        target_ids = [1, 2]
        std_devs = loc._compute_std_devs(estimated, target_ids)
        # At distance ~0 with 2 tags, should be close to multi-tag base
        for i in range(3):
            # Allow some tolerance for distance not being exactly 0
            assert std_devs[i] < loc.single_tag_std_devs[i] or loc.single_tag_std_devs[i] == float('inf')

    def test_single_tag_uses_single_tag_base(self):
        loc = _make_localization()
        tag_pose = loc.field_layout.getTagPose(1)
        assert tag_pose is not None
        estimated = Pose3d(
            tag_pose.translation(), Rotation3d()
        )
        target_ids = [1]
        std_devs = loc._compute_std_devs(estimated, target_ids)
        # Single tag theta should be inf
        assert std_devs[2] == float('inf')

    def test_single_tag_beyond_max_distance_returns_inf(self):
        loc = _make_localization()
        # Place estimated pose very far from any tag
        estimated = _pose3d(x=0.0, y=0.0)
        # Use a tag that's far away (tag 1 is on the far side of the field)
        # Just need avg_dist > single_tag_max_dist
        target_ids = [1]
        tag_pose = loc.field_layout.getTagPose(1)
        assert tag_pose is not None
        dist = tag_pose.toPose2d().translation().distance(
            estimated.toPose2d().translation()
        )
        if dist <= loc.single_tag_max_dist:
            # Move estimated pose further away to ensure rejection
            estimated = _pose3d(x=-10.0, y=-10.0)
        std_devs = loc._compute_std_devs(estimated, target_ids)
        assert all(s == float('inf') for s in std_devs)

    def test_std_devs_increase_with_distance(self):
        loc = _make_localization()
        tag_pose = loc.field_layout.getTagPose(1)
        assert tag_pose is not None

        targets_multi = [1, 2]

        # Close estimate
        close_pose = Pose3d(tag_pose.translation(), Rotation3d())
        close_std = loc._compute_std_devs(close_pose, targets_multi)

        # Far estimate (2m away from tag)
        far_translation = Translation3d(
            tag_pose.X() + 2.0, tag_pose.Y(), tag_pose.Z()
        )
        far_pose = Pose3d(far_translation, Rotation3d())
        far_std = loc._compute_std_devs(far_pose, targets_multi)

        # Far should have larger std devs than close
        assert far_std[0] > close_std[0]
        assert far_std[1] > close_std[1]

    def test_no_tags_returns_single_tag_base(self):
        loc = _make_localization()
        # Empty target list
        std_devs = loc._compute_std_devs(_pose3d(), [])
        assert std_devs == loc.single_tag_std_devs

    def test_unknown_tag_id_returns_single_tag_base(self):
        loc = _make_localization()
        # Tag ID that doesn't exist in the field layout
        target_ids = [999]
        std_devs = loc._compute_std_devs(_pose3d(), target_ids)
        assert std_devs == loc.single_tag_std_devs

    def test_distance_scaling_formula(self):
        """Verify the quadratic scaling formula directly."""
        loc = _make_localization()
        tag_pose = loc.field_layout.getTagPose(1)
        assert tag_pose is not None

        # Place estimate exactly at tag position
        estimated = Pose3d(tag_pose.translation(), Rotation3d())
        target_ids = [1, 2]

        std_devs = loc._compute_std_devs(estimated, target_ids)

        # tag 2 should be at a different position, so avg_dist > 0
        tag2_pose = loc.field_layout.getTagPose(2)
        if tag2_pose is not None:
            dist1 = tag_pose.toPose2d().translation().distance(
                estimated.toPose2d().translation()
            )
            dist2 = tag2_pose.toPose2d().translation().distance(
                estimated.toPose2d().translation()
            )
            avg_dist = (dist1 + dist2) / 2.0
            expected_scale = 1.0 + (avg_dist ** 2 / loc.std_dev_distance_factor)
            for i in range(2):  # x and y
                expected = loc.multi_tag_std_devs[i] * expected_scale
                assert abs(std_devs[i] - expected) < 0.001
