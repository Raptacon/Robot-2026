        """Create a minimal test bundle and verify extraction."""
        with tempfile.TemporaryDirectory() as tmpdir:
            cache_dir = os.path.join(tmpdir, 'fields')
            bundle_path = os.path.join(tmpdir, 'bundle.zip')

            # Build a fake inner zip with config.json and model.glb
