        with tempfile.TemporaryDirectory() as tmpdir:
            # Create a .py file that should be rejected
            with open(os.path.join(tmpdir, 'evil.py'), 'w') as f:
                f.write('import os')
            data, mime = cad.serve_cad_file(tmpdir, 'evil.py')
